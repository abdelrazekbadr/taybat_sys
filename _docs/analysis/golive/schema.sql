create or replace function public.handle_new_user()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
BEGIN
  INSERT INTO public.profiles (id, email, provider)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_app_meta_data->>'provider', 'email')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$function$;

create or replace function public.sync_post_love_count()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
DECLARE
  target_post_id bigint;
BEGIN
  target_post_id := COALESCE(NEW.post_id, OLD.post_id);
  UPDATE community_posts
  SET love_count = (
    SELECT COUNT(*) FROM post_reactions WHERE post_id = target_post_id
  )
  WHERE id = target_post_id;
  RETURN NULL;
END;
$function$;

create or replace function public.create_notification_from_post()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
BEGIN
  IF (
    NEW.public_notification = true AND (
      TG_OP = 'INSERT' OR
      (TG_OP = 'UPDATE' AND (OLD.public_notification IS DISTINCT FROM true))
    )
  ) THEN
    INSERT INTO app_notifications (type, title, body, action_type, action_ref)
    VALUES (
      'new_post',
      NEW.author_name,
      SUBSTRING(NEW.content FROM 1 FOR 120),
      'community_post',
      NEW.id::text
    );
  END IF;
  RETURN NEW;
END;
$function$;

