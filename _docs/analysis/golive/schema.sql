-- Al-Taybat production schema — reconstructed via SQL introspection of the
-- dev project (mbbbdhyhtqkxakmblzmk) on 2026-07-11, because `supabase db dump`
-- requires Docker and this environment's sandbox can't reach the Docker
-- daemon the CLI needs. Every table/column/constraint/policy/trigger/function
-- below was read directly from pg_catalog / information_schema on dev, not
-- guessed. Apply this once, in order, against a freshly created prod project.
--
-- One intentional deviation from dev: dev's `profiles` table has two
-- redundant BEFORE UPDATE triggers calling the same set_updated_at()
-- function (`set_profiles_updated_at` and `trg_profiles_updated_at`) —
-- leftover duplication from migration history. Only one is created here.

