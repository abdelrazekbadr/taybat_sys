create or replace function public.record_point_event(p_track text, p_action_key text, p_reference_id uuid default null::uuid, p_reference_type text default null::text, p_meal_ref_id bigint default null::bigint)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'not authenticated';
  end if;

  if not exists (
    select 1 from membership_point_rules
    where action_key = p_action_key and track = p_track and is_active = true
  ) then return; end if;

  insert into user_point_events
    (user_id, track, action_key, event_date, reference_id, reference_type, meal_ref_id)
  values
    (v_user_id, p_track, p_action_key,
     (now() at time zone 'UTC')::date,
     p_reference_id, p_reference_type, p_meal_ref_id)
  on conflict do nothing;
end;
$function$;

create or replace function public.delete_day_point_event(p_event_date date)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;

  delete from user_point_events
  where user_id    = auth.uid()
    and action_key = 'add_daily_meal'
    and event_date = p_event_date;
end;
$function$;

create or replace function public.get_user_membership(p_user_id uuid)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_window_days          int;
  v_window_start         timestamptz;
  v_committed_points     int;
  v_supporter_points     int;
  v_committed_tier_key   text;
  v_committed_tier_label text;
  v_committed_tier_icon  text;
  v_supporter_tier_key   text;
  v_supporter_tier_label text;
  v_supporter_tier_icon  text;
begin
  select coalesce(value::int, 30) into v_window_days
    from membership_config where key = 'reset_window_days';
  v_window_start := now() - (v_window_days || ' days')::interval;

  select
    coalesce(sum(r.points) filter (where e.track = 'committed'), 0),
    coalesce(sum(r.points) filter (where e.track = 'supporter'), 0)
  into v_committed_points, v_supporter_points
  from user_point_events e
  join membership_point_rules r
    on r.action_key = e.action_key and r.is_active = true
  where e.user_id = p_user_id
    and e.occurred_at >= v_window_start;

  select t.tier_key, t.label_ar, t.icon_key
    into v_committed_tier_key, v_committed_tier_label, v_committed_tier_icon
  from membership_tiers t
  where t.track = 'committed' and t.min_points <= v_committed_points
  order by t.min_points desc limit 1;

  select t.tier_key, t.label_ar, t.icon_key
    into v_supporter_tier_key, v_supporter_tier_label, v_supporter_tier_icon
  from membership_tiers t
  where t.track = 'supporter' and t.min_points <= v_supporter_points
  order by t.min_points desc limit 1;

  v_committed_tier_key   := coalesce(v_committed_tier_key,   'starter');
  v_committed_tier_label := coalesce(v_committed_tier_label, 'مبتدئ');
  v_committed_tier_icon  := coalesce(v_committed_tier_icon,  'tier_starter');
  v_supporter_tier_key   := coalesce(v_supporter_tier_key,   'starter');
  v_supporter_tier_label := coalesce(v_supporter_tier_label, 'مبتدئ');
  v_supporter_tier_icon  := coalesce(v_supporter_tier_icon,  'tier_starter');

  return json_build_object(
    'committed_points',     v_committed_points,
    'supporter_points',     v_supporter_points,
    'committed_tier_key',   v_committed_tier_key,
    'committed_tier_label', v_committed_tier_label,
    'committed_tier_icon',  v_committed_tier_icon,
    'supporter_tier_key',   v_supporter_tier_key,
    'supporter_tier_label', v_supporter_tier_label,
    'supporter_tier_icon',  v_supporter_tier_icon,
    'window_start',         v_window_start
  );
end;
$function$;

create or replace function public.get_community_stats()
 returns table(month text, active_users bigint, avg_health_score numeric, avg_adherence_score numeric, total_meals_logged bigint)
 language sql
 stable security definer
 set search_path to ''
as $function$
  select
    to_char(date_trunc('month', wr.submitted_at), 'YYYY-MM') as month,
    count(distinct wr.user_id)                                as active_users,
    round(avg(wr.health_score)::numeric, 1)                   as avg_health_score,
    round(avg(wr.adherence_score)::numeric, 1)                as avg_adherence_score,
    count(distinct um.id)                                     as total_meals_logged
  from public.users_ratings wr
  left join public.user_meals um
    on date_trunc('month', um.datetime) = date_trunc('month', wr.submitted_at)
  group by date_trunc('month', wr.submitted_at)
  order by 1 desc;
$function$;

create or replace function public.match_documents(query_embedding extensions.vector, match_count integer default 10, filter jsonb default '{}'::jsonb)
 returns table(id bigint, content text, metadata jsonb, similarity double precision)
 language plpgsql
as $function$
#variable_conflict use_column
begin
  return query
  select
    documents.id,
    documents.content,
    documents.metadata,
    1 - (documents.embedding <=> query_embedding) as similarity
  from documents
  where metadata @> filter
  order by documents.embedding <=> query_embedding
  limit match_count;
end;
$function$;

create or replace function public.delete_user_account()
 returns void
 language plpgsql
 security definer
 set search_path to 'public', 'auth'
as $function$
DECLARE
  _uid uuid := auth.uid();
BEGIN
  IF _uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  DELETE FROM public.post_reactions        WHERE user_id    = _uid;
  DELETE FROM public.user_follows          WHERE follower_id = _uid OR target_id = _uid;
  DELETE FROM public.notification_reads    WHERE user_id    = _uid;
  DELETE FROM public.user_point_events     WHERE user_id    = _uid;
  DELETE FROM public.membership_leaderboard_cache WHERE user_id = _uid;
  DELETE FROM public.community_posts       WHERE user_id    = _uid;
  DELETE FROM public.meal_favorites        WHERE user_id    = _uid;
  DELETE FROM public.user_meals            WHERE user_id    = _uid;
  DELETE FROM public.users_ratings         WHERE user_id    = _uid;
  DELETE FROM public.user_preferences      WHERE user_id    = _uid;
  DELETE FROM public.profiles              WHERE id         = _uid;

  DELETE FROM auth.users WHERE id = _uid;
END;
$function$;

create or replace function public.apply_admin_policy_to_public_rls_tables()
 returns void
 language plpgsql
 security definer
 set search_path to 'pg_catalog', 'public'
as $function$
DECLARE
  table_name text;
BEGIN
  FOR table_name IN
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind IN ('r', 'p')
      AND c.relrowsecurity = true
  LOOP
    EXECUTE format(
      'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated',
      table_name
    );

    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON public.%I',
      'admin: full access',
      table_name
    );

    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin())',
      'admin: full access',
      table_name
    );
  END LOOP;
END;
$function$;

