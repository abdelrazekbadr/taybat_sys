-- ---------------------------------------------------------------------------
-- 1. PROFILES TABLE
--    One row per user. Created automatically by trigger on sign-up.
--    Populated progressively: sign-up fills (id, email, provider),
--    complete-profile fills the rest, sets profile_completed = true.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
  id                uuid        PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email             text        NOT NULL,
  name              text,
  gender            text        CHECK (gender IN ('male', 'female')),
  birth_year        integer,
  weight_kg         numeric(5, 1),
  height_cm         numeric(5, 1),
  activity_level    text        CHECK (activity_level IN ('sedentary', 'light', 'moderate', 'active')),
  health_gools_ids  text,
  provider          text        NOT NULL DEFAULT 'email',
  profile_completed boolean     NOT NULL DEFAULT false,
  plan_start_date   date,                          -- set when complete-profile is saved
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

-- Idempotent: add plan_start_date if the table already existed without it
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS plan_start_date date;

-- Idempotent: add health_gools_ids if the table already existed without it
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS health_gools_ids text;

-- ---------------------------------------------------------------------------
-- 1b. HEALTH_GOOLS TABLE (health goals catalog)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.health_gools (
  id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text        NOT NULL,
  name_en    text,
  active     boolean     NOT NULL DEFAULT true,
  image      text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.health_gools ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "health_gools: public read"       ON public.health_gools;
DROP POLICY IF EXISTS "health_gools: service_role write" ON public.health_gools;

CREATE POLICY "health_gools: public read"
  ON public.health_gools FOR SELECT
  USING (active = true);

CREATE POLICY "health_gools: service_role write"
  ON public.health_gools FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

